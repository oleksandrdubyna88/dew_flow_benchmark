namespace Bench.Tests.Telemetry;

/// <summary>The spool fixtures, where they come from, and why there are two of them.
///
/// <para>
/// Neither is hand-authored. Both were produced by <c>dew_flow_mcp</c>'s own <c>SpoolUsageSink</c> — the
/// real emitter — and copied here verbatim, because a fixture written on this side would prove only that
/// this codec agrees with my idea of the other repository, which is exactly the failure a cross-repository
/// contract has to rule out.
/// </para>
///
/// <para>
/// <b>Why two.</b> <c>correlation</c> was added to <c>telemetry/v0</c> ADDITIVELY, and a reader has to
/// handle both shapes: a line written by today's emitter, and a line written before that field existed —
/// which is what any spool already sitting on a disk looks like. One file cannot be both, and the attempt
/// to make it be both is how this was found: feeding a correlated line to the pre-correlation fixture's
/// tests failed with <i>"Expected record.Correlation.IsAttributed to be False … but found True"</i>. The
/// test was right and the file was being asked to do two jobs.
/// </para>
///
/// <list type="table">
///   <item><term><see cref="PreCorrelationLines"/></term><description>the older wire shape, no
///     <c>correlation</c> member at all. Backward compatibility: a reader today must still parse it, and
///     must report the absence as an absence WITH A REASON rather than as an unattributed
///     zero.</description></item>
///   <item><term><see cref="CorrelatedLines"/></term><description>what the emitter writes now, carrying
///     <c>leg</c> and <c>phase</c>. Forward coverage: the field is read, and it is what makes a
///     per-phase report possible at all.</description></item>
/// </list>
///
/// <para>
/// When the emitter's shape changes again, a fixture is REPLACED from a fresh emitter run rather than
/// edited — an edited fixture is a fixture that has quietly stopped being evidence. The correlated one is
/// regenerated by <c>SpoolFixtureTests</c> in <c>dew_flow_mcp</c>, which writes it beside its own test
/// binary for exactly this copy. Deliberately a manual copy: a fixture that regenerated itself on every
/// build would silently absorb the very change it exists to catch.
/// </para></summary>
internal static class Fixture
{
    /// <summary>An emitter line from before <c>correlation</c> existed.</summary>
    public static string PreCorrelationPath => Resolve("mcp-spool-v0-precorrelation.jsonl");

    /// <summary>What the emitter writes today.</summary>
    public static string CorrelatedPath => Resolve("mcp-spool-v0-correlated.jsonl");

    /// <summary>The three pre-correlation lines, in the order the emitter wrote them: answered, refused,
    /// error.</summary>
    public static IReadOnlyList<string> PreCorrelationLines => Read(PreCorrelationPath);

    /// <summary>The three correlated lines, same three outcomes in the same order — so a test can compare
    /// the two shapes on everything except the field that distinguishes them.</summary>
    public static IReadOnlyList<string> CorrelatedLines => Read(CorrelatedPath);

    /// <summary>Both shapes, for the assertions that must hold whichever one a reader meets.</summary>
    public static IEnumerable<(string Shape, IReadOnlyList<string> Lines)> BothShapes =>
        [("pre-correlation", PreCorrelationLines), ("correlated", CorrelatedLines)];

    /// <summary>The correlated spool as a whole file — what an ingester is actually handed. The default
    /// for anything not specifically testing the older shape: a reader is met by today's emitter.</summary>
    public static string CorrelatedText => File.ReadAllText(CorrelatedPath);

    /// <summary>The pre-correlation spool as a whole file.</summary>
    public static string PreCorrelationText => File.ReadAllText(PreCorrelationPath);

    private static string Resolve(string name) =>
        System.IO.Path.Combine(AppContext.BaseDirectory, "Fixtures", name);

    private static IReadOnlyList<string> Read(string path) =>
        [.. File.ReadAllText(path).Split('\n').Select(l => l.Trim('\r')).Where(l => l.Length > 0)];
}
