export const templateDir = (stack, kind, root = TEMPLATES) => path.join(root, stack, kind);
export const readTemplate = (stack, kind, name, root = TEMPLATES) => readFileSync(path.join(templateDir(stack, kind, root), name), 'utf8');

/** Every file under `dir` as a sorted list of `/` paths, dot files included. */
export const filesUnder = dir => readdirSync(dir, { recursive: true, withFileTypes: true }).filter(e => e.isFile()).map(e => path.relative(dir, path.join(e.parentPath, e.name)).split(path.sep).join('/')).sort();

/** `100755`-style mode of a tracked file from `git ls-files -s`, or null when the file is not tracked. */
export async function trackedMode(file) {
  const r = await runBounded('git', ['ls-files', '-s', '--', path.basename(file)], { cwd: path.dirname(file), timeoutMs: 20_000, env: { PATH: '/usr/bin:/bin' } });
  if (!r.ok) throw new Error(r.reason);
  return r.value.stdout.trim() === '' ? null : r.value.stdout.split(' ')[0];
}
