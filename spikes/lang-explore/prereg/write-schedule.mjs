#!/usr/bin/env node
// Writes `inputs/prereg/schedule.json` (F3.S1 (b), PR 5): the tasks and their kinds, the rounds, the mask of all 30 (round, task) cells, the two scoring profiles, the pass and attempt counts, the caps, the pilot's tasks, the A/A's task and
// stack, the read-back rule and the re-run rule. Every value is computed from the schedule module and the pins; nothing is typed. The pilot (`{ aa: { task, stack }, daemon, web }`, the owner's answer to open point 2) is an input the file
// is refused without, validated by the schedule's own `pilotPlan`.
//   node spikes/lang-explore/prereg/write-schedule.mjs [--out <file>] [--check]
// Exit 0 written (or checked equal) | 1 `--check` differs | 4 usage | 5 an input is unreadable or the pilot is refused.
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { fail, ok } from '../../minigit-bench/lib/result.mjs';
import { loadExplore } from '../lib/inputs.mjs';
import { INPUTS, REPO } from '../lib/paths.mjs';
import { MAX_ATTEMPTS, MASKS, STACK_ORDER } from '../lib/series.mjs';
import { PREREG_DIR, STAGE_PILOT } from '../lib/stage-lists.mjs';
import { READBACK_ROUNDS, READBACK_ROW, STAGE_ROUNDS, TASK_KINDS, maskOfSlot, pilotPlan } from '../lib/stage-schedule.mjs';
import { ATTEMPTS_PER_PASS, PASS_COUNT, PROFILES } from '../lib/verdict.mjs';
import { FREEZE_TASKS } from '../lib/workspaces-sources.mjs';
import { runGenerator } from './generator.mjs';

/** The mask of every (round, task) cell: `[{ round, task, csharp, node }]`, all 30, from `maskOfSlot` (the parent's rule, never the seed). */
function maskCells() {
  const rounds = Array.from({ length: STAGE_ROUNDS }, (_, i) => i + 1);
  return rounds.flatMap(round => FREEZE_TASKS.map(task => ({ round, task, ...Object.fromEntries(STACK_ORDER.map(stack => [stack, maskOfSlot({ round, task, stack }).value])) })));
}

/** The number of CPUs in a mask range such as `6-7` (two) or `0-7` (eight). */
const cpuCount = range => range.split('-').reduce((lo, hi) => Number(hi) - Number(lo) + 1);

/** The prose of the mask rule: the places of the tasks in the freeze are those of `FREEZE_TASKS`. */
const maskRuleText = () => `in round r the C# session of task k (${FREEZE_TASKS.map((task, k) => `${task} is ${k}`).join(', ')}) runs on mask A when r + k is odd and on mask B when it is even; the Node session takes the other mask; the seed never decides a mask`;

/** The prose of the scoring rule: the CPU counts are those of the two profiles (the odd passes take the first). */
const scoringRuleText = () => `the odd passes run on the ${cpuCount(PROFILES[0].cpus)}-CPU profile and the even passes on the ${cpuCount(PROFILES[1].cpus)}-CPU profile`;

/** The prose of the pilot's session count: the A/A's twins and each pair's sessions, each with its attempts (a void is re-run once). */
function pilotSessionsText(plan) {
  const [aa, pair] = [plan.aa.sessions.length * MAX_ATTEMPTS, plan.pairs[0].sessions.length * MAX_ATTEMPTS];
  return `at most ${aa + pair * plan.pairs.length}: the A/A ${aa}, each pair ${pair}`;
}

/** The file as an object. `pilot` is the registered pilot; a refusal of `pilotPlan` is a refusal here, naming the field. -> `ok(object)` | `fail`. */
export function buildSchedule({ explore, pilot } = {}) {
  const plan = pilotPlan({ pilot });
  if (!plan.ok) return fail(`the pilot is refused: ${plan.reason}`);
  return ok({
    source: 'generated by spikes/lang-explore/prereg/write-schedule.mjs from lib/stage-schedule.mjs, lib/series.mjs, lib/verdict.mjs and explore.json; nothing here is typed',
    stage: 1, tasks: [...FREEZE_TASKS], kinds: TASK_KINDS, stacks: [...STACK_ORDER], rounds: STAGE_ROUNDS, slots: STAGE_ROUNDS * FREEZE_TASKS.length, dataSessions: STAGE_ROUNDS * FREEZE_TASKS.length * STACK_ORDER.length,
    masks: { A: MASKS.low, B: MASKS.high, rule: maskRuleText(), cells: maskCells() },
    scoring: { passes: PASS_COUNT, attemptsPerPass: ATTEMPTS_PER_PASS, profiles: PROFILES.map(p => ({ name: p.name, cpus: p.cpus })), rule: scoringRuleText() },
    attempts: { perCell: MAX_ATTEMPTS, rerun: 'a void is re-run once, alone, as its own attempt, before the next slot; a second void ends the cell' },
    caps: explore.caps,
    pilot: { aa: { ...pilot.aa, twins: ['a', 'b'] }, daemon: pilot.daemon, web: pilot.web, sessions: pilotSessionsText(plan.value) },
    readback: { row: READBACK_ROW, rounds: [...READBACK_ROUNDS], pairs: `in round ${READBACK_ROUNDS[0]} and in round ${READBACK_ROUNDS[1]} one slot of a daemon task and one of a web task, named from the seed before any result exists`, gate: 'no later slot runs until each session of a read-back slot that counts has its dated line, holds or refuted; a refuted session is void: harness and is re-run once, alone, before any later slot' },
  });
}

const textOf = object => `${JSON.stringify(object, null, 2)}\n`;

/** The command's build. `pilot` defaults to the registered one (`STAGE_PILOT`); the seam is for tests. */
async function build({ pilot, exploreFile }) {
  const explore = loadExplore(exploreFile);
  if (!explore.ok) return explore;
  const built = buildSchedule({ explore: explore.value, pilot });
  return built.ok ? ok(textOf(built.value)) : built;
}

export const main = (argv, say = line => process.stdout.write(`${line}\n`), { pilot = STAGE_PILOT, exploreFile = path.join(INPUTS, 'explore.json') } = {}) => runGenerator({ argv, build: () => build({ pilot, exploreFile }), defaultOut: path.join(REPO, PREREG_DIR, 'schedule.json'), say });

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) process.exitCode = await main(process.argv.slice(2));
