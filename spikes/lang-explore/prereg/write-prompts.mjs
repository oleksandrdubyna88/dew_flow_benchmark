#!/usr/bin/env node
// Writes `inputs/prereg/prompts-lang.json` (F3.S1 (b), PR 5): the bare template and its sha256, and per task and stack the prompt text, the stack sentence, the framework sentence of a web task and the sha256 of the workspace's
// `STATEMENT.md` as published at W (read from the registered `hashes-lang.txt`; with `--task-repo` every hash is checked against the checkout's file as well). Everything is computed from the engine's own code (`stagePrompts`) and the
// registered pins and hashes; nothing is typed.
//   node spikes/lang-explore/prereg/write-prompts.mjs [--out <file>] [--check] [--task-repo <checkout of the task repository at W>]
// Exit 0 written (or checked equal) | 1 `--check` differs | 4 usage | 5 an input is unreadable or a hash does not hold.
import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { fail, ok } from '../../minigit-bench/lib/result.mjs';
import { loadExplore } from '../lib/inputs.mjs';
import { INPUTS, REPO } from '../lib/paths.mjs';
import { PREREG_DIR } from '../lib/stage-lists.mjs';
import { stagePrompts } from '../lib/stage-prompts.mjs';
import { quickExplore } from '../lib/quick.mjs';
import { TASK_KINDS } from '../lib/stage-schedule.mjs';
import { FREEZE_STACKS, FREEZE_TASKS, folderOf, freezeTasks } from '../lib/workspaces-sources.mjs';
import { frameworkSentence, packagesInputs } from '../lib/workspace-quick.mjs';
import { runGenerator } from './generator.mjs';

const HASHES_FILE = path.join(REPO, 'spikes', 'lang-bench', 'inputs', 'hashes-lang.txt');
const sha256 = bytes => createHash('sha256').update(bytes).digest('hex');

/** The `STATEMENT.md` hashes of `hashes-lang.txt`: `{ '<stack>/<NN-slug>': sha256 }` for the statements only. */
export function statementHashes(hashesText) {
  const rows = hashesText.split('\n').map(l => /^([0-9a-f]{64}) {2}(\S+)\/STATEMENT\.md$/.exec(l)).filter(Boolean);
  return Object.fromEntries(rows.map(m => [m[2], m[1]]));
}

/** The sentences saying where a statement hash is not the bytes of the published workspace (`read(folder)` gives the file's bytes or `null`). `[]` when all twelve hold. */
export function statementProblems({ hashes, folders, read }) {
  return folders.flatMap(folder => {
    const bytes = read(folder);
    if (hashes[folder] === undefined) return [`hashes-lang.txt has no STATEMENT.md hash for ${folder}`];
    if (bytes === null) return [`the published workspace ${folder} has no STATEMENT.md to check its hash against`];
    return sha256(bytes) === hashes[folder] ? [] : [`${folder}/STATEMENT.md is not the published one: its sha256 is ${sha256(bytes).slice(0, 12)}, the registered hash is ${hashes[folder].slice(0, 12)}`];
  });
}

/** One task and stack's entry. */
function entryOf({ prompts, stack, task, folder, hashes, explore, record }) {
  const web = TASK_KINDS[task.id] === 'web';
  return { text: prompts.prompts[stack].text, sha256: prompts.prompts[stack].sha256, stackSentence: prompts.prompts[stack].stackSentence, frameworkSentence: web ? frameworkSentence(explore, stack, record) : null, statementSha256: hashes[folder] };
}

/** The file as an object: pure over the pins (`explore`, the quick profile), the package record and the statement hashes. -> `ok(object)` | `fail`. */
export function buildPromptsFile({ explore, record, hashes }) {
  const tasks = freezeTasks(explore);
  if (!tasks.ok) return tasks;
  const prompts = stagePrompts(explore);
  const missing = tasks.value.flatMap(task => FREEZE_STACKS.map(stack => folderOf(task, stack))).filter(folder => hashes[folder] === undefined);
  if (missing.length > 0) return fail(`hashes-lang.txt has no STATEMENT.md hash for ${missing.join(', ')}`);
  const entries = Object.fromEntries(tasks.value.map(task => [task.id, Object.fromEntries(FREEZE_STACKS.map(stack => [stack, entryOf({ prompts, stack, task, folder: folderOf(task, stack), hashes, explore, record })]))]));
  return ok({
    source: 'generated by spikes/lang-explore/prereg/write-prompts.mjs from lib/stage-prompts.mjs, the registered pins and hashes-lang.txt; nothing here is typed. The bare prompt of the parent\'s section 4.5 with the limits sentence of F3\'s closed point 10',
    template: prompts.template, templateSha256: prompts.templateSha256, tasks: entries,
  });
}

const textOf = object => `${JSON.stringify(object, null, 2)}\n`;

/** The git-free reader of a checkout's published statements: `<root>/<folder>/STATEMENT.md`. */
const readerOf = root => folder => { try { return readFileSync(path.join(root, folder, 'STATEMENT.md')); } catch { return null; } };

/** The statement hashes file's text: `ok(text)` | `fail` naming the file (a missing file is a refusal, never a throw). */
function hashesText(file) {
  try {
    return ok(readFileSync(file, 'utf8'));
  } catch (e) {
    return fail(`${file} cannot be read: ${e.code ?? e.message}`);
  }
}

/** What `build` reads: the explore file, the package record and the statement hashes. -> `ok({ profile, record, hashes })` | `fail`. */
function inputsOf({ hashesFile, exploreFile, home }) {
  const [explore, packages, text] = [loadExplore(exploreFile), packagesInputs(), hashesText(hashesFile)];
  const unread = [explore, packages, text].find(r => !r.ok);
  return unread ?? ok({ profile: quickExplore(explore.value, home), record: packages.value.record, hashes: statementHashes(text.value) });
}

/** The sentence for a statement hash that is not the published file of the `--task-repo` checkout (every folder of the freeze), or null when none is named or all hold. */
function checkoutProblem({ inputs, root }) {
  if (!root) return null;
  const folders = freezeTasks(inputs.profile).value.flatMap(task => FREEZE_STACKS.map(stack => folderOf(task, stack)));
  const problems = statementProblems({ hashes: inputs.hashes, folders, read: readerOf(root) });
  return problems.length === 0 ? null : problems.join('; ');
}

/** The command's build: the file's text, after the checks of `--task-repo`. */
async function build({ values, hashesFile = HASHES_FILE, exploreFile = path.join(INPUTS, 'explore.json'), home = os.homedir() }) {
  const read = inputsOf({ hashesFile, exploreFile, home });
  if (!read.ok) return read;
  const built = buildPromptsFile({ explore: read.value.profile, record: read.value.record, hashes: read.value.hashes });
  if (!built.ok) return built;
  const problem = checkoutProblem({ inputs: read.value, root: values['task-repo'] });
  return problem ? fail(problem) : ok(textOf(built.value));
}

/** The command: -> the exit code. The seams (`hashesFile`, `exploreFile`, `home`) are for tests. */
export const main = (argv, say = line => process.stdout.write(`${line}\n`), seams = {}) => runGenerator({ argv, extra: { 'task-repo': { type: 'string' } }, build: values => build({ values, ...seams }), defaultOut: path.join(REPO, PREREG_DIR, 'prompts-lang.json'), say });

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) process.exitCode = await main(process.argv.slice(2));
export { FREEZE_TASKS };
