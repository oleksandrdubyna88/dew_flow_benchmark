#!/usr/bin/env node
// Part 7 (CHH) tables, from ../../data/part7 and ../../data/part6/metrics6.json only (no access to the machine the experiment ran on).
//   node research/local-model-coding/harness/part6/make-tables7.mjs     → prints the Part 7 section on stdout
// ../make-tables.mjs imports part7Tables() and appends the section to ../../tables.md after Part 6's.
import { existsSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { tcrit, welch } from './make-tables6.mjs';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const D6 = join(ROOT, 'data', 'part6');
const D7 = join(ROOT, 'data', 'part7');
const rd = (base, f) => JSON.parse(readFileSync(join(base, f), 'utf8'));
const CHH = ['CHH1', 'CHH2', 'CHH3'];
const P6 = ['C1', 'C2', 'C3', 'CR1', 'CR2', 'CR3', 'SRS1', 'SRS2', 'SRS3'];
const mean = (xs) => xs.reduce((s, x) => s + x, 0) / xs.length;
const f = (v, d = 1) => Number(v).toFixed(d);
const usd = (v) => `$${v.toFixed(2)}`;
const tk = (n) => n.toLocaleString('en-US');
const stepOrder = (n) => Number(n.match(/^(\d+)/)[1]);

export function part7Tables() {
  const out = []; const p = (s = '') => out.push(s);
  const M = rd(D6, 'metrics6.json');
  const SC = rd(D7, 'judge-abs/scores.json'); const KEY = rd(D7, 'judge-abs/key.json'); const HC = rd(D7, 'judge-abs/handcheck.json');
  const CF = rd(D7, 'coai-findings.json'); const CC = rd(D7, 'coai-cost.json'); const JK = rd(D7, 'judge-coai/key.json');
  const HO = rd(D7, 'haiku-outcomes.json');
  const inv = Object.fromEntries(Object.entries(JK).map(([l, a]) => [a, l]));
  const arm = (a, x) => rd(D7, `arms/${a}/${x}.json`);
  const kindCost = (a, ks) => Object.values(M[a].steps).filter((s) => ks.includes(s.kind)).reduce((n, s) => n + s.cost, 0);
  const kindMin = (a, ks) => Math.round(Object.values(M[a].steps).filter((s) => ks.includes(s.kind)).reduce((n, s) => n + s.wall_s, 0) / 60);

  p('## 11. Part 7 — CHH: the classic scheme with two focused Haiku reviewers, on the same task as Part 6 (3 arms)');
  p();
  p('> Generated by `harness/part6/make-tables7.mjs` from `data/part7/` and `data/part6/metrics6.json`. The SAME task, plan and base as §10, run after it, so the CHH arms');
  p('> can be put beside C, CR and SRS (§11.9). **Hindsight:** the two reviewer focuses were chosen from what Part 6 missed on this task ([results.md](results.md) §7e).');
  p('> **Cost** is Claude-only (the coai providers\' cost was not measured), counted per session by its last attempt\'s result ([incidents.md](incidents.md) §2h).');
  p('> **Active min** leaves out limit waits; **Elapsed min** includes them.');
  p();

  // 11.1
  p('### 11.1 Cost, time and attempts per arm (Claude only)');
  p();
  p('| Arm | Claude-only $ | Active min | Elapsed min | Attempts (sessions) |');
  p('|---|---|---|---|---|');
  for (const a of CHH) {
    const m = M[a]; const sess = Object.values(m.steps).reduce((n, s) => n + (s.sessions ?? 0), 0);
    p(`| ${a} | ${usd(m.cost)} | ${m.active_min} | ${m.span_min}${a === 'CHH1' ? ' †' : ''} | ${m.attempts} (${sess}) |`);
  }
  p(`| **CHH mean** | **${usd(mean(CHH.map((a) => M[a].cost)))}** (${usd(Math.min(...CHH.map((a) => M[a].cost)))}–${usd(Math.max(...CHH.map((a) => M[a].cost)))}) | **${f(mean(CHH.map((a) => M[a].active_min)), 0)}** (${Math.min(...CHH.map((a) => M[a].active_min))}–${Math.max(...CHH.map((a) => M[a].active_min))}) | ${Math.min(M.CHH2.span_min, M.CHH3.span_min)}–${Math.max(M.CHH2.span_min, M.CHH3.span_min)} (CHH2 and CHH3) | |`);
  p();
  p('† CHH1\'s last fix step (`6-fix`) hit the owner\'s spend limit after 31 minutes of work and waited from 00:53 to 04:08 UTC (3 h 16 min); 12 of its 14 attempts ended at once in a 429 error ([incidents.md](incidents.md) §2i). Active minutes leave the wait out.');
  p();

  // 11.2
  p('### 11.2 Per step (from `data/part6/metrics6.json`)');
  p();
  p('| Arm | Step | Model | Cost (Claude only) | Active min | Attempts |');
  p('|---|---|---|---|---|---|');
  for (const a of CHH) for (const [name, s] of Object.entries(M[a].steps).sort((x, y) => stepOrder(x[0]) - stepOrder(y[0]))) p(`| ${a} | ${name} | ${s.model} | ${usd(s.cost)} | ${Math.round(s.wall_s / 60)} | ${s.attempts} |`);
  p();
  p('By role (Claude-only cost; active min in brackets):');
  p();
  p('| Arm | Sonnet code | Haiku A (decision tracer) | Haiku B (test truth) | Sonnet fix of both (hfix) | Opus review | Sonnet fix | Sonnet coai gate | Total |');
  p('|---|---|---|---|---|---|---|---|---|');
  const c = (a, k) => `${usd(kindCost(a, [k]))} (${kindMin(a, [k])})`;
  for (const a of CHH) p(`| ${a} | ${c(a, 'code')} | ${c(a, 'hA')} | ${c(a, 'hB')} | ${c(a, 'hfix')} | ${c(a, 'review')} | ${c(a, 'fix')} | ${c(a, 'gate')} | ${usd(M[a].cost)} |`);
  p(`| **Mean** | ${usd(mean(CHH.map((a) => kindCost(a, ['code']))))} | ${usd(mean(CHH.map((a) => kindCost(a, ['hA']))))} | ${usd(mean(CHH.map((a) => kindCost(a, ['hB']))))} | ${usd(mean(CHH.map((a) => kindCost(a, ['hfix']))))} | ${usd(mean(CHH.map((a) => kindCost(a, ['review']))))} | ${usd(mean(CHH.map((a) => kindCost(a, ['fix']))))} | ${usd(mean(CHH.map((a) => kindCost(a, ['gate']))))} | ${usd(mean(CHH.map((a) => M[a].cost)))} |`);
  p();
  p(`No step of the three arms started a subagent (\`byModel\` shows no model other than the step's own above $0.05 in any step; the read-only steps refuse the \`Agent\` and \`Task\` tools, and a search of the streams for those tool names finds none).`);
  p();

  // 11.3
  p('### 11.3 Objective gate (on each arm\'s final commit)');
  p();
  p('| Arm | Build | Format | MCP suite (total / passed / skipped / new failures) | TS suite (total / new failures) | Scenarios (of 43) present / passing | Commits | Diff | Changed lines: tests / src / docs |');
  p('|---|---|---|---|---|---|---|---|---|');
  for (const a of CHH) {
    const o = arm(a, 'objective');
    p(`| ${a} | ${o.build ? 'ok' : 'FAIL'} | ${o.format ? 'ok' : 'FAIL'} | ${o.mcp.total} / ${o.mcp.passed} / ${o.mcp.skipped} / ${o.mcp.failedNew.length} | ${o.ts.total} / ${o.ts.failedNew.length} | ${o.scenariosPresentCount} / ${o.scenariosPassingCount} | ${o.commits} | ${o.diff.shortstat} | ${o.diff.changedLines.tests} / ${o.diff.changedLines.src} / ${o.diff.changedLines.docs} |`);
  }
  p();
  for (const a of CHH) {
    const o = arm(a, 'objective');
    for (const [id, v] of Object.entries(o.scenarios ?? {})) if (!v.present || v.passing !== 'passed') p(`- ${a} ${id}: present = ${v.present}, passing = "${v.passing}" — \`${v.name}\``);
    for (const t of o.mcp.failedNew) p(`- ${a} new MCP failure: \`${t}\``);
  }
  p();

  // 11.4
  p('### 11.4 The Opus review (before the Sonnet fixes), from `notes/review.json`');
  p();
  p('| Arm | Findings | Blocking / major / minor | Verdict |');
  p('|---|---|---|---|');
  const rev = {};
  for (const a of CHH) { const r = arm(a, 'review'); const n = (s) => r.findings.filter((x) => x.severity === s).length; rev[a] = { bm: n('blocking') + n('major'), total: r.findings.length }; p(`| ${a} | ${r.findings.length} | ${n('blocking')} / ${n('major')} / ${n('minor')} | ${r.verdict} |`); }
  p();
  p(`Blocking + major per arm: ${CHH.map((a) => rev[a].bm).join(' / ')} (mean ${f(mean(CHH.map((a) => rev[a].bm)), 2)}). Part 6, same task: C 1 / 1 / 2, CR 1 / 2 / 2, SRS 2 / 2 / 1.`);
  p();

  // 11.5
  p('### 11.5 What the two Haiku reviewers found, and what the fixer did (`notes/hA.json`, `notes/hB.json`, `notes/hfix.md`)');
  p();
  p('Haiku A traces each plan decision at every site; Haiku B checks that each test tests what it claims and passes on every CI machine. The outcomes are read by hand from the fixer\'s notes (`data/part7/haiku-outcomes.json`).');
  p();
  p('| Arm | Reviewer | Findings (blocking / major / minor) | Fixed | Plan amended (code was right) | Not fixed |');
  p('|---|---|---|---|---|---|');
  const tot = { n: 0, bm: 0, fixed: 0, amended: 0, not: 0, nB: 0, mB: 0 };
  for (const a of CHH) for (const [who, file, idp] of [['A', 'hA', 'A'], ['B', 'hB', /^(B|F)/]]) {
    const fs_ = arm(a, file).findings; const sev = (s) => fs_.filter((x) => x.severity === s).length;
    const oc = (k) => fs_.filter((x) => HO[a][x.id]?.outcome === k).length;
    p(`| ${a} | ${who} | ${fs_.length} (${sev('blocking')} / ${sev('major')} / ${sev('minor')}) | ${oc('fixed')} | ${oc('plan-amended')} | ${oc('not-fixed')} |`);
    if (who === 'B') { tot.nB += fs_.length; tot.mB += sev('major') + sev('blocking'); }
    tot.n += fs_.length; tot.bm += sev('blocking') + sev('major'); tot.fixed += oc('fixed'); tot.amended += oc('plan-amended'); tot.not += oc('not-fixed');
  }
  p(`| **All** | | **${tot.n}** (${tot.bm} blocking or major) | **${tot.fixed}** | **${tot.amended}** | **${tot.not}** |`);
  p();
  p('The three findings of Haiku A that name a defect an arm of Part 6 had shipped (each opened at the commit the reviewer read, and in the final code):');
  p();
  p('| Arm | Finding | Defect | Shipped in Part 6 by | Fixed by the hfix step | In the final code |');
  p('|---|---|---|---|---|---|');
  p('| CHH1 | A1 (blocking) | `DeepseekRuntime` inherits `CodexRuntime.QuotaKeyOf` = "codex", so a DeepSeek refusal parks every Codex row | C1 (hand-checked major) | `d398446b`, red test first | gone: `DeepseekRuntime` overrides the key with an empty one |');
  p('| CHH2 | A2 (major) | `AgyError.Parse` reads one line, so the issue\'s own multi-line `AGY_ERROR` sample is not an error | SRS2 and SRS3 (named by their Opus reviews; the Part 6 coai judge listed it as missed) | `d0809c4d`, red test first | gone: the parser reads a balanced object over several lines |');
  p('| CHH3 | A1 (major) | a transient refusal ahead of a hopeless one hides it (`FirstOf`-type pick) | SRS2 (hand-checked major edge case) | `6a0097f5`, red test first | gone: the refusals are ranked, spent first |');
  p();
  p(`Haiku B's findings are mostly about tests that cannot fail or that do not run the decision (${tot.nB} findings, ${tot.mB} major): a cap test that stays under its bound with the cap removed, an assertion that a dropped row passes, a hook on one store only, no test that runs \`RoundEngine\` (CHH2 F3, CHH3 B1), a roster that no test builds with a cooling row. None of the ${tot.nB} is about a CI machine (time zone, path length, platform).`);
  p();

  // 11.6
  p('### 11.6 Quality — the absolute blind judge (one Opus session per diff, anchored rubric, 2 runs)');
  p();
  p('| Arm | Overall (runs) | Correctness | Tests | Conventions | Simplicity | Defects per run (B / M / m) | Redacted words |');
  p('|---|---|---|---|---|---|---|---|');
  const dstr = (r) => r.defects.map((d) => ({ blocking: 'B', major: 'M', minor: 'm' }[d.severity])).sort().join('') || '—';
  for (const a of CHH) { const rs = SC[a]; const pair = (k) => rs.map((r) => r[k]).join(' / '); p(`| ${a} | **${f(mean(rs.map((r) => r.overall)))}** (${pair('overall')}) | ${pair('correctness')} | ${pair('tests')} | ${pair('conventions')} | ${pair('simplicity')} | ${rs.map(dstr).join(' / ')} | ${KEY.redactions[a]} |`); }
  const g = (k) => f(mean(CHH.flatMap((a) => SC[a].map((r) => r[k]))), 2);
  p(`| **CHH mean** | **${g('overall')}** | ${g('correctness')} | ${g('tests')} | ${g('conventions')} | ${g('simplicity')} | | |`);
  p();
  p('The hand check (`data/part7/judge-abs/handcheck.json`, 2026-10-30):');
  p();
  p('| Arm | Judge\'s major | Hand check | Evidence |');
  p('|---|---|---|---|');
  for (const m of HC.part7.majors) p(`| ${m.arm} | ${m.finding} | ${m.verdict}; severity ${m.severity} | ${m.evidence} |`);
  p();
  for (const r of HC.part7.renamed) p(`CHH1 ${r.scenario} renamed: plan name \`${r.plan}\`; code name \`${r.code}\`. ${r.note}.`);
  p();

  // 11.7
  p('### 11.7 The coai code gate');
  p();
  const judged = {};
  for (const a of CHH) {
    const v = rd(D7, `judge-coai/${inv[a]}/verdict.json`); const code = CF[a].filter((r) => r.stage === 'code');
    const rows = code.flatMap((r) => r.findings.map((x) => ({ round: r.number, ...x, j: v.findings.find((y) => y.round === r.number && y.index === x.index) })));
    const cnt = (k) => rows.filter((x) => x.j.verdict === k).length;
    judged[a] = { v, code, rows, n: rows.length, real: cnt('real'), partly: cnt('partly'), not: cnt('not_real'), acc: rows.filter((x) => x.decision === 'accept').length, score: v.score };
  }
  p('| Arm | Plan rounds (verdicts; findings, all rejected as frozen) | Code rounds (verdicts) | Code findings | Severity as coai gave it (B / M / m) | Accepted by the gate agent | Rejected |');
  p('|---|---|---|---|---|---|---|');
  for (const a of CHH) {
    const j = judged[a]; const pl = CF[a].filter((r) => r.stage === 'plan'); const sev = (s) => j.rows.filter((x) => x.severity === s).length;
    p(`| ${a} | ${pl.length} (${pl.map((r) => `${r.verdict}; ${r.findings.length}`).join(', ')}) | ${j.code.length} (${j.code.map((r) => r.verdict).join(', ')}) | ${j.n} | ${sev('Blocking')} / ${sev('Major')} / ${sev('Minor')} | ${j.acc} | ${j.n - j.acc} |`);
  }
  p();
  p('The blind judge of those findings (one Opus session per arm; the gate agent\'s decisions and the providers not shown; it worked in the arm\'s clone):');
  p();
  p('| Arm | Findings | Real | Partly | Not real | Judge score (1–10) | Accepted by the gate agent |');
  p('|---|---|---|---|---|---|---|');
  for (const a of CHH) { const j = judged[a]; p(`| ${a} | ${j.n} | ${j.real} | ${j.partly} | ${j.not} | ${j.score} | ${j.acc} |`); }
  const t = (k) => CHH.reduce((n, a) => n + judged[a][k], 0);
  p(`| **All three** | **${t('n')}** | **${t('real')}** | **${t('partly')}** | **${t('not')}** | mean ${f(mean(CHH.map((a) => judged[a].score)), 2)} | **${t('acc')}** |`);
  p();
  const reals = CHH.flatMap((a) => judged[a].rows.filter((x) => x.j.verdict === 'real').map((x) => `${a} \"${x.title}\" (coai: ${x.severity.toLowerCase()}; judge: ${x.j.severity_right === 'yes' ? x.severity.toLowerCase() : x.j.severity_right}; gate agent: ${x.decision})`));
  p(`Findings rated real: ${reals.join('; ') || 'none'}. Important defects the judge says the review missed: ${CHH.map((a) => `${a} ${judged[a].v.missed.length}`).join(', ')}.`);
  p();
  p('Tokens that the coai server reported (`cost.tokensIn` / `cost.tokensOut` per round; tokens, not dollars; `data/part7/coai-cost.json`):');
  p();
  p('| Arm | Plan round(s) in / out | Code round(s) in / out | Total in | Total out |');
  p('|---|---|---|---|---|');
  for (const a of CHH) {
    const rs = CC[a]; const fmt = (st) => rs.filter((r) => r.stage === st).map((r) => `${tk(r.tokensIn)} / ${tk(r.tokensOut)}`).join('; ');
    p(`| ${a} | ${fmt('plan')} | ${fmt('code')} | ${tk(rs.reduce((n, r) => n + r.tokensIn, 0))} | ${tk(rs.reduce((n, r) => n + r.tokensOut, 0))} |`);
  }
  p();

  // 11.8
  p('### 11.8 Behaviour — the frozen mutation checks (data/part7/arms/<arm>/mutation.json, harness/part6/mutate6.mjs)');
  p();
  p('The same eight mutants as §10.7, with the anchors for the CHH arms added to `mutate6.mjs` before any CHH result. Per intended scenario test: **+** it failed (caught), **−** it exists by that name but still PASSED.');
  p();
  const mj = Object.fromEntries(CHH.map((a) => [a, arm(a, 'mutation')])); const ids = mj.CHH1.mutants.map((x) => x.id);
  p(`| Arm | Killed | Tests in scope (baseline) | .NET SDK | ${ids.map((i) => i.split('-')[0]).join(' | ')} |`);
  p(`|---|---|---|---|${ids.map(() => '---').join('|')}|`);
  const cellOf = (x) => `${x.verdict.toLowerCase()} (${x.intended.map((i) => `${i.scenario} ${i.present ? (i.caught ? '+' : '−') : '?'}`).join(', ')}; ${x.killedBy.length} test${x.killedBy.length === 1 ? '' : 's'})`;
  for (const a of CHH) p(`| ${a} | ${mj[a].summary.killed}/${mj[a].summary.applicable} | ${mj[a].baseline.tests} | ${a === 'CHH3' ? '10.0.114' : '10.0.113'} | ${mj[a].mutants.map(cellOf).join(' | ')} |`);
  p();
  const a1 = arm('CHH3', 'mutation.attempt1-sdk-upgraded-mid-run');
  p(`CHH3's first run (kept as \`mutation.attempt1-sdk-upgraded-mid-run.json\`): ${a1.summary.killed} of ${a1.summary.applicable + a1.summary.notApplicable.length} mutants applied and killed; ${a1.summary.notApplicable.map((x) => x.split('-')[0]).join(' and ')} were "not applicable" because the .NET SDK was upgraded from 10.0.113 to 10.0.114 by the system at 05:19:54 UTC, in the middle of the run, and their builds failed (NETSDK1042). The run was repeated whole; its numbers are in the table. All 24 mutants (8 × 3 arms) were killed, and none of the intended tests missed.`);
  p();

  // 11.9
  p('### 11.9 The same task, four schemes (Part 6 and Part 7; the CHH arms ran after the others, with a hindsight advantage)');
  p();
  p('| Scheme | Arms | Claude-only $ mean (range) | Active min mean | Opus blocking + major (mean) | Judge overall mean (arms) | Judge majors after the hand check | coai findings real / partly / not | coai judge scores |');
  p('|---|---|---|---|---|---|---|---|---|');
  const SCH = [['C', ['C1', 'C2', 'C3']], ['CR', ['CR1', 'CR2', 'CR3']], ['SRS', ['SRS1', 'SRS2', 'SRS3']], ['CHH', CHH]];
  const rv6 = (a) => { const r = P6.includes(a) ? rd(D6, `arms/${a}/review.json`) : arm(a, 'review'); return r.findings.filter((x) => x.severity !== 'minor').length; };
  const S6 = rd(D6, 'judge-abs/scores.json'); const hc6 = rd(D6, 'judge-abs/handcheck.json');
  const J6 = rd(D6, 'judge-coai/key.json'); const CF6 = rd(D6, 'coai-findings.json');
  const jc = (a) => {
    const isP6 = P6.includes(a); const key = isP6 ? J6 : JK; const base = isP6 ? D6 : D7; const cf = isP6 ? CF6 : CF;
    const label = Object.entries(key).find(([, x]) => x === a)[0]; const v = rd(base, `judge-coai/${label}/verdict.json`);
    const code = cf[a].filter((r) => r.stage === 'code'); const rows = code.flatMap((r) => r.findings.map((x) => v.findings.find((y) => y.round === r.number && y.index === x.index)));
    return { real: rows.filter((x) => x.verdict === 'real').length, partly: rows.filter((x) => x.verdict === 'partly').length, not: rows.filter((x) => x.verdict === 'not_real').length, score: v.score };
  };
  for (const [s, as] of SCH) {
    const costs = as.map((a) => M[a].cost); const scores = as.map((a) => (P6.includes(a) ? S6[a] : SC[a]));
    const ov = scores.map((rs) => mean(rs.map((r) => r.overall)));
    const rmaj = s === 'CHH' ? 0 : as.reduce((n, a) => n + hc6.majors.filter((m) => m.arm === a && m.verdict === 'real' && /^major/.test(m.severity)).length, 0);
    const j = as.map(jc);
    p(`| ${s} | ${as.join(', ')} | ${usd(mean(costs))} (${usd(Math.min(...costs))}–${usd(Math.max(...costs))}) | ${f(mean(as.map((a) => M[a].active_min)), 0)} | ${f(mean(as.map(rv6)), 2)} | ${f(mean(ov), 2)} (${ov.map((x) => f(x)).join(' / ')}) | ${rmaj} | ${j.reduce((n, x) => n + x.real, 0)} / ${j.reduce((n, x) => n + x.partly, 0)} / ${j.reduce((n, x) => n + x.not, 0)} | ${j.map((x) => x.score).join(' / ')} |`);
  }
  p();
  p('Is the extra cost of CHH measured? Welch\'s t test on the three arms of each scheme (a |t| below the 5 % limit is a difference that the spread of the runs can make alone):');
  p();
  p('| Pair (first minus second) | Difference of means | t | df | 5 % limit of \\|t\\| |');
  p('|---|---|---|---|---|');
  const cs = Object.fromEntries(SCH.map(([s2, as]) => [s2, as.map((a) => M[a].cost)]));
  for (const o of ['C', 'CR', 'SRS']) { const r = welch(cs.CHH, cs[o]); p(`| CHH − ${o} | +${usd(r.diff)} | ${f(r.t, 2)} | ${f(r.df, 1)} | ${f(tcrit(r.df), 1)} |`); }
  p();
  p('CHH\'s "judge majors after the hand check" is 0: the one major the judge named (CHH3, a failing suite) was not confirmed. SRS3\'s cost keeps its $3.79 of subagent cost ($15.83 mean for SRS without it).');
  p();
  return out.join('\n');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1] && existsSync(D7)) console.log(part7Tables());
