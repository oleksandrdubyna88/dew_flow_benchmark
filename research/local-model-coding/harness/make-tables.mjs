#!/usr/bin/env node
// Regenerates ../tables.md from ../data only (no access to the machine the experiment ran on is needed).
//   node research/local-model-coding/harness/make-tables.mjs
// Inputs: data/metrics.json (time, cost and tokens per arm, step, attempt and model — written by metrics.mjs),
// data/arms/<arm>/{objective,survival,fill-test,fill-prod}.json, data/arms/<arm>/filler-requests.jsonl,
// data/judges/absolute/scores.json, data/judges/group-v{1,2}/{key,run1-verdict,run2-verdict}.json.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const D = join(ROOT, 'data');
const read = (f) => (existsSync(join(D, f)) ? JSON.parse(readFileSync(join(D, f), 'utf8')) : null);
const lines = (f) => (existsSync(join(D, f)) ? readFileSync(join(D, f), 'utf8').split('\n').filter(Boolean).map((l) => JSON.parse(l)) : []);
const { prices, report } = read('metrics.json');
const ORDER = ['C', 'C2', 'C3', 'C4', 'V', 'VT', 'Q1', 'Q2', 'Q3', 'Q4', 'H1', 'H2', 'H3', 'H4', 'T1', 'T2', 'T3', 'T4', 'O1', 'O2', 'O3', 'O4', 'S1', 'S2', 'S3', 'S4', 'D1', 'D2', 'D3', 'D4', 'SR1', 'SR2', 'SR3', 'SR4', 'DR1', 'DR2', 'DR3', 'DR4', 'CR1', 'CR2', 'CR3', 'CR4', 'CH1', 'CH2', 'CH3', 'CH4'];
const ARMS = ORDER.filter((a) => report[a]);
const CLASSIC = ['C', 'C2', 'C3', 'C4'];
const GROUP = { C: 'classic', C2: 'classic', C3: 'classic', C4: 'classic', V: 'vLLM drafts, thinking off', VT: 'vLLM drafts, thinking on' };
const group = (a) => GROUP[a] ?? (a.startsWith('CR') ? 'Sonnet codes → a fresh Haiku reviews + fixes → Opus checks → Sonnet fixes' : a.startsWith('CH') ? 'Sonnet codes → a fresh Haiku reviews + fixes → Opus checks → Haiku fixes' : a.startsWith('Q') ? 'skeleton + Qwen fill' : a.startsWith('H') ? 'skeleton + Haiku fill' : a.startsWith('T') ? 'Opus tasks → Haiku codes → Sonnet per task' : a.startsWith('SR') ? 'Sonnet tasks → Haiku codes → a fresh Haiku reviews + fixes → Opus checks → Haiku fixes' : a.startsWith('DR') ? 'Haiku codes the story → a fresh Haiku reviews + fixes → Opus checks → Haiku fixes' : a.startsWith('O') ? 'Opus tasks → Haiku codes → Opus checks → Haiku fixes' : a.startsWith('S') ? 'Sonnet tasks → Haiku codes → Opus checks → Haiku fixes' : 'Haiku codes the story → Opus checks → Haiku fixes');
const mean = (xs) => (xs.length ? xs.reduce((s, x) => s + x, 0) / xs.length : null);
const f = (v, d = 1) => (v == null || Number.isNaN(v) ? 'n/a' : Number(v).toFixed(d));
const usd = (v) => (v == null || Number.isNaN(v) ? 'n/a' : `$${v.toFixed(2)}`);
const k = (n) => `${(n / 1000).toFixed(1)}k`;
const out = [];
const p = (s = '') => out.push(s);

const row = (a) => {
  const r = report[a];
  const ms = Object.values(r.models);
  const sum = (key) => ms.reduce((n, u) => n + (u[key] ?? 0), 0);
  const steps = Object.values(r.steps).flat();
  const filler = steps.filter((x) => x.how === 'script').reduce((n, x) => n + (x.cost ?? 0), 0);
  return { a, min: r.wallSeconds / 60, cost: r.cost, est: r.costEstimated, filler, out: sum('output'),
    sonnetOut: r.models['claude-sonnet-5-5']?.output ?? 0, opusOut: r.models['claude-opus-5-5']?.output ?? 0,
    cacheRead: sum('cacheRead'), cacheWrite: sum('cacheWrite') + sum('input'), vllm: r.vllm };
};
const rows = ARMS.map(row);
const band = (key) => { const xs = rows.filter((r) => CLASSIC.includes(r.a)).map((r) => r[key]); return xs.length ? [Math.min(...xs), mean(xs), Math.max(...xs)] : null; };

p('# Tables — generated');
p();
p('> Generated by `harness/make-tables.mjs` from `data/` only (§10, Part 6, by `harness/part6/make-tables6.mjs` from `data/part6/`; §11, Part 7, by `harness/part6/make-tables7.mjs` from `data/part7/`). Do not edit by hand: change the data or the script and');
p('> regenerate. The narrative and its caveats are in [results.md](results.md).');
p();
p('## 1. Time, cost and tokens per arm');
p();
p('Work time excludes every pause and crash (each attempt is timed on its own). Cost is Claude Code\'s own');
p('`total_cost_usd` per session at list prices; `*` = part of it estimated for an attempt a crash interrupted (tokens');
p('— and for the T arms "Work min" is the SUM of their steps, whose parallel tasks overlap: their elapsed time is in §4b —');
p('from its transcript, priced with the unit prices fitted below). The filler is the local model (no API cost) or Haiku.');
p();
p('| Arm | Scheme | Work min | Claude $ | of it: filler $ | Sonnet out | Opus out | Cache read | Cache write + input | Filler requests / tokens / GPU or API time |');
p('|---|---|---|---|---|---|---|---|---|---|');
for (const r of rows) {
  const v = r.vllm ? `${r.vllm.requests} / ${k(r.vllm.promptTokens + r.vllm.completionTokens)} / ${Math.round(r.vllm.busySeconds / 60)} min` : '—';
  p(`| ${r.a} | ${group(r.a)} | ${Math.round(r.min)} | ${usd(r.cost)}${r.est ? '*' : ''} | ${r.filler ? usd(r.filler) : '—'} | ${k(r.sonnetOut)} | ${k(r.opusOut)} | ${f(r.cacheRead / 1e6)}M | ${k(r.cacheWrite)} | ${v} |`);
}
p();
const b = (key, fmt) => { const x = band(key); return x ? x.map(fmt).join(' / ') : 'n/a'; };
p(`**Classic band** (C, C2, C3, C4 — one configuration run four times; min / mean / max): work ${b('min', (v) => `${Math.round(v)} min`)};`);
p(`cost ${b('cost', usd)}; Sonnet output ${b('sonnetOut', k)}; cache read ${b('cacheRead', (v) => `${f(v / 1e6)}M`)}.`);
p();
p('**Unit prices fitted on the sessions with a host cost** (used only for the estimated attempts):');
p();
p('| Model | Output $/Mtok | Cache read $/Mtok | Cache write + input $/Mtok | Fitted on | Max error on those sessions |');
p('|---|---|---|---|---|---|');
for (const [m, x] of Object.entries(prices)) p(`| ${m} | ${f(x.perMtok.output, 2)} | ${f(x.perMtok.cacheRead, 3)} | ${f(x.perMtok.cacheWriteAndInput, 2)} | ${x.fittedOn} | ${f(x.maxRelErr * 100, 1)} % |`);
p();
p();
p('The Haiku row comes only from Claude Code\'s own small internal Haiku calls; its near-zero cache coefficient is noise');
p('and no reported value uses it. The H arms\' filler cost is NOT fitted: each Haiku fill request carries the host\'s own cost.');
p();
p('## 2. Per step');
p();
p('| Arm | Steps (attempt: minutes, $) |');
p('|---|---|');
for (const a of ARMS) {
  const parts = Object.entries(report[a].steps).map(([s, at]) => `${s} ${at.map((x) => `a${x.attempt}: ${x.wallSeconds == null ? '?' : Math.round(x.wallSeconds / 60)} min ${usd(x.cost ?? x.costEst)}${x.cost == null && x.how !== 'script' ? '*' : ''}`).join(', ')}`);
  p(`| ${a} | ${parts.join(' · ')} |`);
}
p();
p('## 3. Objective gate (on each arm\'s final commit)');
p();
p('| Arm | Build | MCP suite new failures | Environment failures (not counted) | TS suite new failures | Format (changed files) | Generator check | Scenarios present | Leftover markers / placeholders | Diff |');
p('|---|---|---|---|---|---|---|---|---|---|');
for (const a of ARMS) {
  const o = read(`arms/${a}/objective.json`);
  if (!o) { p(`| ${a} | not run | | | | | | | | |`); continue; }
  p(`| ${a} | ${o.build ? 'ok' : 'FAIL'} | ${o.mcp.failedNew.length} | ${(o.mcp.failedEnvironment ?? []).length} | ${o.ts.failedNew.length} | ${o.format ? 'ok' : 'FAIL'} | ${o.generatorCheck ? 'ok' : 'FAIL'} | ${o.scenariosPresentCount}/12 | ${o.markersLeft?.length ?? '—'} / ${o.placeholdersLeft?.length ?? '—'} | ${o.diff.shortstat} |`);
}
p();
p('## 3b. The step-2 review (Opus, before the fixes)');
p();
p('| Arm | Findings | Blocking / major / minor | Verdict |');
p('|---|---|---|---|');
for (const a of ARMS) {
  const r = read(`arms/${a}/${a}-review.json`);
  if (!r) { p(`| ${a} | not reviewed yet | | |`); continue; }
  const c = (s) => (r.findings ?? []).filter((x) => x.severity === s).length;
  p(`| ${a} | ${(r.findings ?? []).length} | ${c('blocking')} / ${c('major')} / ${c('minor')} | ${r.verdict} |`);
}
p();
p('## 4. The fill and its survival (skeleton arms)');
p();
p('Survival = share of the filler\'s meaningful lines (not only braces or punctuation) still present after the polish');
p('and in the final commit — whitespace-insensitive, in any file the arm changed (main measure); strict = the same file,');
p('the exact trimmed line (lower bound). Compile errors after a fill are a LOWER bound when a syntax error is present.');
p();
p('| Arm | Test regions (filled / rejected) | Prod regions (filled / rejected) | Compile errors after test fill / prod fill | Survival tests: polish → final (strict) | Survival prod: polish → final (strict) | Diff lines: skeleton / fill / polish / fixes |');
p('|---|---|---|---|---|---|---|');
const pct = (x) => (x == null ? 'n/a' : `${Math.round(x * 100)} %`);
for (const a of ARMS.filter((x) => /^[QH]/.test(x))) {
  const s = read(`arms/${a}/survival.json`);
  if (!s) { p(`| ${a} | not measured yet | | | | | |`); continue; }
  const ft = s.fill.test; const fp = s.fill.prod;
  p(`| ${a} | ${ft?.filled ?? 0} / ${ft?.rejected.length ?? 0} | ${fp?.filled ?? 0} / ${fp?.rejected.length ?? 0} | ${ft?.compileErrors ?? '—'} / ${fp?.compileErrors ?? '—'} | ${pct(s.byKind.test.afterPolish)} → ${pct(s.byKind.test.final)} (${pct(s.byKind.test.strictFinal)}) | ${pct(s.byKind.prod.afterPolish)} → ${pct(s.byKind.prod.final)} (${pct(s.byKind.prod.strictFinal)}) | ${s.diffLines.skeleton} / ${s.diffLines.fill} / ${s.diffLines.polish} / ${s.diffLines.fixes} |`);
}
p();
p('## 4b. The task arms (T: Opus splits, Sonnet reviews each task; O: Opus splits, no task review; S: Sonnet splits, no task review; SR: S + a fresh Haiku review of the whole stories before Opus — Haiku codes every task)');
p();
p('Cost per role from the host (\`metrics.json\`); Haiku survival = Haiku\'s meaningful added lines still present, whitespace-insensitive,');
p('in any file the arm changed in its final commit (\`t-survival.json\`, from the per-task diffs the harness kept).');
p();
p('| Arm | Elapsed (start → done) | Tasks / batches (parallel at most) | Split $ | Haiku $ (all tasks) | Sonnet task reviews $ | Fresh Haiku review $ | Final Opus review $ | Final fixes $ | Haiku lines → kept | Lines the task reviews changed | Final review: findings (major) |');
p('|---|---|---|---|---|---|---|---|---|---|---|---|');
for (const a of ARMS.filter((x) => /^[TOS]/.test(x))) {
  const tm = lines(`arms/${a}/timing.jsonl`); const t0 = Date.parse(tm.find((x) => x.kind === 'start')?.start_utc); const t1 = Date.parse(tm.find((x) => x.kind === 'arm-done')?.done_utc);
  const el = Number.isFinite(t0) && Number.isFinite(t1) ? `${Math.round((t1 - t0) / 60000)} min` : 'n/a';
  const b = read(`arms/${a}/tasks/batches.json`); const ts = read(`arms/${a}/t-survival.json`); const rv = read(`arms/${a}/${a}-review.json`);
  const st = report[a].steps; const g = (re) => Object.entries(st).filter(([kk]) => re.test(kk)).flatMap(([, x]) => x).reduce((q, x) => q + (x.cost ?? x.costEst ?? 0), 0);
  const par = b ? Math.max(...b.batches.map((x) => x.length)) : 0;
  const maj = (rv?.findings ?? []).filter((x) => x.severity !== 'minor').length;
  p(`| ${a} | ${el} | ${b ? Object.keys(b.tasks).length : '?'} / ${b ? b.batches.length : '?'} (${par}) | ${usd(g(/split/))} | ${usd(g(/-code$/))} | ${usd(g(/^3-t/))} | ${a.startsWith('SR') ? usd(g(/hreview/)) : '—'} | ${usd(g(/^4-review/))} | ${usd(g(/^5-fix/))} | ${ts ? `${ts.haikuLines} → ${pct(ts.keptFinal)}` : 'n/a'} | ${ts ? (ts.reviewChangedLines ?? '— (no task review)') : 'n/a'} | ${rv ? `${(rv.findings ?? []).length} (${maj})` : 'n/a'} |`);
}
p();
p('## 5. Filler requests');
p();
p('| Arm | Requests | Prompt tokens | Completion tokens | Thinking on / off | Finish reasons | Sum of request times | Filler cost |');
p('|---|---|---|---|---|---|---|---|');
for (const a of ARMS.filter((x) => !CLASSIC.includes(x))) {
  const q = lines(`arms/${a}/filler-requests.jsonl`);
  if (!q.length) continue;
  const s = (key) => q.reduce((n, x) => n + (x[key] ?? 0), 0);
  const by = (key) => Object.entries(q.reduce((o, x) => ({ ...o, [String(x[key])]: (o[String(x[key])] ?? 0) + 1 }), {})).map(([kk, v]) => `${kk}: ${v}`).join(', ');
  p(`| ${a} | ${q.length} | ${k(s('prompt_tokens'))} | ${k(s('completion_tokens'))} | ${by('think')} | ${by('finish_reason')} | ${Math.round(s('wall_s') / 60)} min | ${q.some((x) => x.cost_usd != null) ? usd(s('cost_usd')) : '$0 (local)'} |`);
}
p();
p('## 6. Quality — the absolute blind judge (one Opus session per diff, anchored rubric, 2 runs)');
p();
const abs = read('judges/absolute/scores.json') ?? {};
p('| Arm | Overall (runs) | Correctness | Tests | Conventions | Simplicity | Defects per run (B = blocking, M = major, m = minor) |');
p('|---|---|---|---|---|---|---|');
for (const a of ARMS) {
  const vs = abs[a] ?? [];
  if (!vs.length) { p(`| ${a} | not judged yet | | | | | |`); continue; }
  const j = (key) => vs.map((v) => v[key]).join(' / ');
  p(`| ${a} | **${f(mean(vs.map((v) => v.overall)))}** (${j('overall')}) | ${j('correctness')} | ${j('tests')} | ${j('conventions')} | ${j('simplicity')} | ${vs.map((v) => (v.defects ?? []).map((d) => ({ blocking: 'B', major: 'M', minor: 'm' })[d.severity] ?? '?').join('') || '—').join(' / ')} |`);
}
p();
p('## 7. Quality — the earlier GROUP judges (one session ranks V, C, C2, VT together; 2 runs, labels permuted)');
p();
for (const [name, dir] of [['v1 — read the uncorrected objective files (superseded)', 'group-v1'], ['v2 — corrected objective files', 'group-v2']]) {
  const key = read(`judges/${dir}/key.json`);
  if (!key) continue;
  p(`**${name}**`);
  p();
  p('| Arm | Run 1 overall | Run 2 overall | Rank run 1 | Rank run 2 |');
  p('|---|---|---|---|---|');
  const v = ['run1', 'run2'].map((r) => read(`judges/${dir}/${r}-verdict.json`));
  const armOf = (r, L) => key[r][L];
  for (const a of ['C2', 'V', 'C', 'VT']) {
    const cells = ['run1', 'run2'].map((r, i) => { const L = Object.keys(key[r]).find((x) => armOf(r, x) === a); return { s: v[i].scores[L]?.overall, rank: v[i].ranking.indexOf(L) + 1 }; });
    p(`| ${a} | ${cells[0].s} | ${cells[1].s} | ${cells[0].rank} | ${cells[1].rank} |`);
  }
  p();
}
p('## 8. Behaviour — the frozen mutation checks (data/arms/<arm>/mutation.json, harness/mutate.mjs)');
p();
p('Each mutant breaks one spec decision in the arm\'s final code; the arm\'s scenario classes are re-run against it. **Killed** = some test');
p('failed. Per intended scenario test: **+** it failed (caught), **−** it exists by its exact name but still PASSED (missed), **r** no test has the');
p('exact name and a renamed test caught it (from `killedBy`).');
p();
p('| Arm | Killed | M1 junction-first (S5.5.2, S5.6.7) | M6 rootless (S5.5.4) | M2 no planner arm (S5.6.4, S5.6.5) | M3 disk confined (S5.6.1, S5.6.8) | M4 web confined (S5.6.1, S5.6.4) | M5 flags accepted (S5.6.6) |');
p('|---|---|---|---|---|---|---|---|');
for (const a of ARMS) {
  const m = read(`arms/${a}/mutation.json`);
  if (!m) { p(`| ${a} | not run | | | | | | |`); continue; }
  const by = Object.fromEntries(m.mutants.map((x) => [x.id.split('-')[0], x]));
  const cell = (id) => { const x = by[id]; if (!x) return 'n/a'; const it = x.intended ?? [];
    const marks = it.map((i) => (i.present ? (i.caught ? '+' : '**−**') : 'r')).join(' ');
    return `${x.verdict === 'killed' ? 'killed' : `**${x.verdict}**`}${marks ? ` (${marks})` : ''}`; };
  const killed = m.mutants.filter((x) => x.verdict === 'killed').length;
  p(`| ${a} | ${killed}/${m.mutants.length} | ${['M1', 'M6', 'M2', 'M3', 'M4', 'M5'].map(cell).join(' | ')} |`);
}
p();
p('## 9. What the fixers did with the review\'s findings (data/fix-outcomes.json)');
p();
p('Classified per finding from the fixer\'s own note only (one Opus session, then hand-checked on D4 and O2): fixed / partly / not fixed /');
p('rejected. The fixer is Sonnet in C, V, VT, Q, H and T, Haiku in O, D and S.');
p();
const fo = read('fix-outcomes.json') ?? {};
p('| Arm | Fixer | Findings (major) | Fixed | Partly | Not fixed | Rejected | Left open (partly + not), majors open |');
p('|---|---|---|---|---|---|---|---|');
const tally = {};
for (const a of ARMS) {
  const x = fo[a]; if (!x) continue;
  const n = (o) => x.findings.filter((y) => y.outcome === o).length;
  const maj = x.findings.filter((y) => y.severity !== 'minor');
  const open = x.findings.filter((y) => y.outcome === 'partly' || y.outcome === 'not-fixed');
  const majOpen = open.filter((y) => y.severity !== 'minor').length;
  const fixer = /^[ODS]/.test(a) ? 'Haiku' : 'Sonnet';
  const g = group(a); tally[g] ??= { n: 0, open: 0, maj: 0, majOpen: 0 };
  tally[g].n += x.findings.length; tally[g].open += open.length; tally[g].maj += maj.length; tally[g].majOpen += majOpen;
  p(`| ${a} | ${fixer} | ${x.findings.length} (${maj.length}) | ${n('fixed')} | ${n('partly')} | ${n('not-fixed')} | ${n('rejected')} | ${open.length}, ${majOpen} |`);
}
p();
p('| Scheme | Findings (major) | Left open | Majors left open |');
p('|---|---|---|---|');
for (const [g, t] of Object.entries(tally)) p(`| ${g} | ${t.n} (${t.maj}) | ${t.open} (${pct(t.n ? t.open / t.n : null)}) | ${t.majOpen} of ${t.maj} |`);
p();
// Part 6 (a different task; its own section, generated from data/part6 by part6/make-tables6.mjs)
if (existsSync(join(D, 'part6'))) out.push((await import('./part6/make-tables6.mjs')).part6Tables());
if (existsSync(join(D, 'part7'))) out.push((await import('./part6/make-tables7.mjs')).part7Tables());
writeFileSync(join(ROOT, 'tables.md'), out.join('\n'));
console.log(`tables.md written: ${ARMS.length} arms`);
